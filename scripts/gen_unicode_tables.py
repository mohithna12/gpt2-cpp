#!/usr/bin/env python3
"""Generate src/unicode_tables.h: the character classes GPT-2's pre-tokenizer regex uses.

    's|'t|'re|'ve|'m|'ll|'d| ?\\p{L}+| ?\\p{N}+| ?[^\\s\\p{L}\\p{N}]+|\\s+(?!\\S)|\\s+

The reference tokenizer is HF `tokenizers` (Rust, Oniguruma regex), whose Unicode tables need
not match Python's unicodedata. So each class is read off the reference pre-tokenizer itself:
a code point is a letter iff "a"+cp stays one piece, a number iff "1"+cp does, "other" iff
"!"+cp does, and whitespace otherwise. unicodedata is only used to report disagreements.

    python scripts/gen_unicode_tables.py [--out src/unicode_tables.h]

The output is committed; the C++ build doesn't need Python or tokenizers.
"""
import argparse
import unicodedata

CLASSES = ("letter", "number", "space")


def probe():
    from transformers import AutoTokenizer

    tok = AutoTokenizer.from_pretrained("gpt2")
    pt = tok.backend_tokenizer.pre_tokenizer
    one = lambda s: len(pt.pre_tokenize_str(s)) == 1  # noqa: E731

    cls = {}
    for cp in range(0x110000):
        if 0xD800 <= cp < 0xE000:
            continue  # surrogates aren't valid in UTF-8; the C++ decoder rejects them
        ch = chr(cp)
        hits = [name for name, lead in (("letter", "a"), ("number", "1"), ("other", "!"))
                if one(lead + ch)]
        if len(hits) > 1:
            raise SystemExit(f"U+{cp:04X} matches several classes: {hits}")
        cls[cp] = hits[0] if hits else "space"
    # Whitespace must behave as \s: cp + "\n" is a single whitespace run.
    for cp, c in cls.items():
        if c == "space" and not one(chr(cp) + "\n"):
            raise SystemExit(f"U+{cp:04X} classified as space but doesn't split like \\s")
    return cls


def unicodedata_class(cp):
    ch = chr(cp)
    cat = unicodedata.category(ch)
    if cat[0] == "L":
        return "letter"
    if cat[0] == "N":
        return "number"
    if ch.isspace():
        return "space"
    return "other"


def ranges(cls, name):
    out = []
    for cp in sorted(cls):
        if cls[cp] != name:
            continue
        if out and out[-1][1] == cp - 1:
            out[-1][1] = cp
        elif out and out[-1][1] + 1 == 0xD800 and cp == 0xE000:
            out[-1][1] = cp  # never split a range across the surrogate gap
        else:
            out.append([cp, cp])
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="src/unicode_tables.h")
    args = ap.parse_args()

    import tokenizers

    cls = probe()
    diffs = [cp for cp in cls if cls[cp] != unicodedata_class(cp)]
    print(f"{len(diffs)} code points differ from unicodedata {unicodedata.unidata_version}",
          "(reference wins)")
    for cp in diffs[:10]:
        print(f"  U+{cp:04X} reference={cls[cp]} unicodedata={unicodedata_class(cp)}")

    lines = [
        "#pragma once",
        "// GENERATED by scripts/gen_unicode_tables.py -- do not edit.",
        f"// Probed from HF tokenizers {tokenizers.__version__} (GPT-2 ByteLevel pre-tokenizer).",
        "// Sorted, disjoint, inclusive code point ranges. Code points in no table are \"other\".",
        "",
        "#include <cstdint>",
        "",
        "namespace gpt2::unicode {",
        "",
        "struct Range {",
        "    uint32_t lo, hi;",
        "};",
    ]
    for name in CLASSES:
        rs = ranges(cls, name)
        print(f"{name}: {sum(1 for c in cls.values() if c == name)} code points, {len(rs)} ranges")
        lines += ["", f"inline constexpr Range k{name.capitalize()}[] = {{"]
        row = []
        for lo, hi in rs:
            row.append(f"{{0x{lo:X}, 0x{hi:X}}},")
            if len(row) == 5:
                lines.append("    " + " ".join(row))
                row = []
        if row:
            lines.append("    " + " ".join(row))
        lines.append("};")
    lines += ["", "}  // namespace gpt2::unicode", ""]
    with open(args.out, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
